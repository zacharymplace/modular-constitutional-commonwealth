#!/usr/bin/env python3
"""Produce/check the structural package report; no legal or operational assessment."""
from pathlib import Path
import argparse, re, datetime, subprocess
repo = Path(__file__).resolve().parents[1]
root = repo / 'constitutional-draft/formal_constitution_v0.4'
report = repo / 'reports/v04_package_audit.md'
args = argparse.ArgumentParser()
args.add_argument('--check', action='store_true')
check = args.parse_args().check
schedules = sorted((root / 'schedules').glob('*.md'))
charters = sorted((root / 'system-charters').glob('*.md'))
codes = sorted((root / 'implementation-codes').glob('*.md'))
assert len(schedules) == 15 and len(charters) == 5 and len(codes) == 5
required = [root / n for n in ['README.md', 'index.md', 'core_constitution.md', 'cross_reference_matrix.md']] + schedules + charters + codes
assert all(p.is_file() for p in required)
state = lambda p: 'scaffold' if 'Scaffold only.' in p.read_text() else 'populated draft'
assert {p.name for p in codes if state(p) == 'scaffold'} == {'fiscal_reporting_code.md', 'transition_implementation_code.md'}
assert all(len(p.read_text().splitlines()) > 50 for p in charters + [p for p in codes if state(p) != 'scaffold'])
resolved = 0
for p in required:
    for ref in re.findall(r'`([^`\n]+\.md)`', p.read_text()):
        candidates = [q for q in [repo / ref, root / ref, p.parent / ref] if q.is_file()]
        if not candidates and '/' not in ref:
            candidates = list(repo.rglob(ref))
        assert candidates, f'Unresolved file reference: {p.relative_to(repo)}: {ref}'
        resolved += 1
algorithmic = (root / 'implementation-codes/algorithmic_audit_code.md').read_text()
for boundary in ['An audit does not itself authorize deployment', 'the higher authority controls.', 'It does not create new sovereign powers.']:
    assert boundary in algorithmic, boundary
if check:
    old = report.read_text()
    verified = re.search(r'^Verified at: (.+)$', old, re.M).group(1)
    revision = re.search(r'^Source baseline: `([^`]+)`', old, re.M).group(1)
else:
    verified = datetime.datetime.now(datetime.timezone.utc).isoformat()
    revision = subprocess.check_output(['git', '-C', str(repo), 'rev-parse', 'HEAD'], text=True).strip()
lines = ['# v0.4 Package Audit', '', 'Generated by: `scripts/audit-v04-package.py`.', f'Verified at: {verified}', f'Source baseline: `{revision}` (package plus the described summary reconciliation).', '', 'Scope: current working-tree package inventory, file references, draft/scaffold states, and explicit Algorithmic Audit authority boundaries.', 'This is not legal validity, exhaustive substantive consistency, external review, or operational validation.', '', '## File inventory', '', '| File | Lines | State |', '|---|---:|---|']
for p in required:
    label = state(p) if p in codes else 'populated draft' if p in charters else 'package document'
    lines.append(f'| `{p.relative_to(root)}` | {len(p.read_text().splitlines())} | {label} |')
lines += ['', '## Check results', '', f'- All {len(required)} expected files present; 15 schedules and five charters.', f'- {resolved} local file references resolved.', '- Three populated draft implementation codes; two remaining scaffolds.', '- Algorithmic Audit preserves controlling authority and does not grant deployment or sovereign powers.', '', '## Boundaries and remaining work', '', 'Fiscal Reporting and Transition remain scaffold-only and unauthorized by this cycle.', 'Keep the existing core, schedules, charters, and populated implementation-code texts unchanged.', 'The existing package pressure test remains analysis, not proof that all concerns are resolved.', 'Further implementation drafting requires a separate bounded decision.', 'Lifecycle remains build / active; no maturity, legal adoption, or production-readiness promotion.', '']
content = '\n'.join(lines)
if check:
    assert report.read_text() == content, 'Package report is stale; regenerate with the named producer.'
else:
    report.write_text(content)
print(f'PASS: {len(required)} files, {resolved} references, declared boundaries; report {"checked" if check else "generated"}.')
